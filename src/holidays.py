"""Календарь праздников РФ.
"""

import pandas as pd

# "месяц-день" -> название
HOLIDAYS = {
    "12-31": "Новый год (31 дек)",
    "01-01": "1 января",
    "01-02": "Новогодние каникулы",
    "01-03": "Новогодние каникулы",
    "01-04": "Новогодние каникулы",
    "01-05": "Новогодние каникулы",
    "01-06": "Новогодние каникулы",
    "01-07": "Новогодние каникулы",
    "01-08": "Новогодние каникулы",
    "02-14": "14 февраля",
    "02-23": "23 февраля",
    "03-08": "8 марта",
    "05-01": "1 мая",
    "05-09": "9 мая",
    "06-12": "12 июня",
    "11-04": "4 ноября",
}


def holiday_name(dates: pd.Series) -> pd.Series:
    """Название праздника для каждой даты или NaN, если день обычный."""
    return dates.dt.strftime("%m-%d").map(HOLIDAYS)


def is_holiday(dates: pd.Series) -> pd.Series:
    """Индикатор 1[день праздник] для каждой даты."""
    return holiday_name(dates).notna().astype(int)